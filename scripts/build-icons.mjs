/**
 * Reads the Lucide icon set from node_modules and emits src/icons.js as a
 * name -> inner-markup map. Keeps the shipped site free of any icon CDN and
 * guarantees the glyphs are the real Lucide geometry, not a hand-drawn guess.
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { divisions, services } from "../src/data/catalog.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ICON_DIR = resolve(ROOT, "node_modules/lucide-static/icons");
const TEMPLATE = resolve(ROOT, "src/template.html");
const OUT = resolve(ROOT, "assets/js/icons.js");

const names = [
  "printer", "credit-card", "wallet", "banknote", "landmark", "briefcase-business",
  "search", "ticket", "graduation-cap", "shield-check", "file-text", "id-card",
  "receipt", "car", "heart", "users", "building-2", "phone", "mail", "map-pin",
  "clock", "arrow-right", "arrow-up-right", "chevron-down", "chevron-right", "menu",
  "x", "check", "plus", "send", "square-stack", "panels-top-left", "user-round-cog",
  "badge-check", "headset", "calendar-days", "clipboard-list", "badge-indian-rupee",
  "plane", "bus", "route", "navigation", "globe", "monitor", "laptop", "cpu",
  "hard-drive", "smartphone", "scroll-text", "tags", "award", "list-checks",
  "notebook-pen", "lock", "eye", "user-plus", "users-round", "circle-check",
  "circle-alert", "loader", "external-link", "chevron-left", "chevron-up", "house",
  "store", "warehouse", "factory", "briefcase-medical", "heart-pulse", "key", "home",
  "sun", "moon", "zap", "wheat", "scale", "hand-coins", "circle-dollar-sign",
  "file-check-2", "folder-open", "layers", "layout-panel-top", "wrench", "package",
  "server", "wifi", "book-open", "truck", "plus-circle", "info",
];

const out = {};
const missing = [];

/** Every icon name the catalogue and the template actually reference. */
async function referencedNames() {
  const fromCatalog = [
    ...divisions.map((d) => d.icon),
    ...services.map((s) => s.icon),
  ];
  const template = await readFile(TEMPLATE, "utf8");
  const fromTemplate = [...template.matchAll(/data-icon="([a-z0-9-]+)"/g)].map((m) => m[1]);
  return [...fromCatalog, ...fromTemplate];
}

const referenced = await referencedNames();
const wanted = new Set([...names, ...referenced]);

for (const name of wanted) {
  let raw;
  try {
    raw = await readFile(resolve(ICON_DIR, `${name}.svg`), "utf8");
  } catch {
    missing.push(name);
    continue;
  }
  // Keep only the shape elements between <svg ...> and </svg>.
  const inner = raw
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s+/g, " ")
    .trim();
  out[name] = inner;
}

if (missing.length) {
  console.error(`Missing icons: ${missing.join(", ")}`);
  process.exit(1);
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");

const file = `/* Lucide icon geometry, generated by scripts/build-icons.mjs from
 * node_modules/lucide-static (ISC License, lucide.dev). Do not hand-edit.
 * Rendered with <svg class="icon" viewBox="0 0 24 24" aria-hidden="true"> so
 * stroke colour, width and cap all come from the design system. */
export const icons = {
${body}
};

/** Renders an icon as an inline SVG string. */
export function icon(name, className = "icon") {
  const body = icons[name];
  if (!body) throw new Error(\`Unknown icon: \${name}\`);
  return \`<svg class="\${className}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">\${body}</svg>\`;
}
`;

await writeFile(OUT, file, "utf8");
console.log(`Wrote ${Object.keys(out).length} icons to ${OUT}`);
