/**
 * Downloads the two brand typefaces from Google Fonts and self-hosts them.
 * Result: assets/fonts/*.woff2 + assets/css/fonts.css (local @font-face rules).
 * Nothing on the shipped site reaches out to fonts.googleapis.com.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FONT_DIR = resolve(ROOT, "assets/fonts");
const CSS_DIR = resolve(ROOT, "assets/css");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const FAMILIES = [
  { name: "Archivo", query: "family=Archivo:wght@100..900&display=swap", slug: "archivo" },
  {
    name: "Public Sans",
    query: "family=Public+Sans:wght@100..900&display=swap",
    slug: "public-sans",
  },
];

async function main() {
  await mkdir(FONT_DIR, { recursive: true });
  await mkdir(CSS_DIR, { recursive: true });

  const blocks = [];

  for (const fam of FAMILIES) {
    const url = `https://fonts.googleapis.com/css2?${fam.query}`;
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`CSS fetch failed for ${fam.name}: ${res.status}`);
    let css = await res.text();

    // Google returns one @font-face per unicode subset. Keep latin + latin-ext only.
    const faces = css.split("@font-face").filter((block) => block.includes("url("));
    let kept = 0;

    for (const face of faces) {
      const subsetMatch = face.match(/\/\*\s*([a-z-]+)\s*\*\//);
      const unicodeRange = face.match(/unicode-range:\s*([^;]+);/);
      const srcMatch = face.match(/url\((https:[^)]+\.woff2)\)/);
      if (!srcMatch) continue;
      const range = unicodeRange ? unicodeRange[1] : "";
      // Keep the base latin subset (contains U+0000-00FF) and latin-ext.
      const isLatin = /U\+0000-00FF/i.test(range);
      const isLatinExt = /U\+0100-02(AF|BA)/i.test(range);
      if (!isLatin && !isLatinExt) continue;

      const fileName = `${fam.slug}-${isLatin ? "latin" : "latin-ext"}.woff2`;
      const bin = await fetch(srcMatch[1], { headers: { "User-Agent": UA } });
      if (!bin.ok) throw new Error(`Font file fetch failed: ${srcMatch[1]}`);
      await writeFile(resolve(FONT_DIR, fileName), Buffer.from(await bin.arrayBuffer()));

      const weight = face.match(/font-weight:\s*([^;]+);/)?.[1] ?? "400";
      const style = face.match(/font-style:\s*([^;]+);/)?.[1] ?? "normal";
      blocks.push(
        `@font-face {\n  font-family: "${fam.name}";\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url("../fonts/${fileName}") format("woff2");\n  unicode-range: ${range.trim()};\n}`
      );
      kept += 1;
    }
    console.log(`${fam.name}: ${kept} subset file(s) written`);
  }

  const header = `/* Self-hosted brand typefaces. SIL Open Font License 1.1.\n   Archivo - Omnibus-Type / Public Sans - United States Digital Service\n   Generated by scripts/fetch-fonts.mjs - do not hand-edit. */\n\n`;
  await writeFile(resolve(CSS_DIR, "fonts.css"), header + blocks.join("\n\n") + "\n");
  console.log(`Wrote ${resolve(CSS_DIR, "fonts.css")}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
